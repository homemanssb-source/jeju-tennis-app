--  1) 변경 공지 등록 (일반 공지, 상단 고정): 동호인·주니어 모두 11/22 순연
--  2) 앞선 "동호인 정상 진행" 공지는 고정 해제하고 제목에 변경됨 표시
--  3) 동호인 대회 취소·변경 마감을 11/21 17:00 KST 로 열기 (주니어는 이미 열려 있음)
--  멱등.

insert into public.notices (title, content, pinned, notice_type)
select
  '[변경] 동호인·주니어 모두 11/22(일)로 순연',
  $notice$앞서 동호인 개인복식 대회는 오늘 정상 진행으로 안내드렸으나, 우천으로 동호인 대회도 내일로 순연합니다. 혼선을 드려 죄송합니다.

제4회 제주시테니스협회장배 동호인 개인복식 대회와 주니어 선수권 대회 모두 내일(11월 22일 일)로 순연합니다. 오늘(11월 21일 토)은 경기가 없습니다.

■ 동호인 개인복식 대회 → 내일(11월 22일 일)로 순연
 - 같은 장소, 같은 시간에 진행합니다.
 - 3팀 1조 예선은 진행하지 않고, 전 부서 순위결정전 후 본선 토너먼트를 진행합니다.
 - 기존 대진은 유지되지 않습니다. 새 대진표와 코트배정표는 오늘(11월 21일) 저녁 8시에 앱과 밴드에 공개합니다.

■ 주니어 선수권 대회 → 내일(11월 22일 일)로 순연 (앞선 안내와 같습니다)
 - 같은 장소, 같은 시간에 진행합니다.
 - 모든 부서 예선 없이 토너먼트로 진행하며, 콘솔레이션은 진행하지 않습니다.
 - 기존 대진은 유지되지 않습니다. 새 대진표와 코트배정표는 오늘(11월 21일) 저녁 8시에 앱과 밴드에 공개합니다.

■ 참가 신청 및 불참 처리 (두 대회 공통)
 - 기존 참가 신청은 그대로 유효합니다. 다시 신청하실 필요가 없습니다.
 - 내일 참가가 어려우면 오늘(11월 21일) 17시까지 앱에서 직접 신청 취소 또는 파트너 변경을 해 주시기 바랍니다.
 - 기한 이후에는 새 대진 편성에 들어가므로 변경이 어렵습니다.

 [신청 취소 방법]
 ① 앱 하단 '신청확인' 메뉴 → '내 신청 내역'
 ② 전화번호와 PIN 6자리 입력 후 조회 (PIN 초기값은 전화번호 뒷 6자리)
 ③ 해당 대회의 '신청 취소' 버튼 선택
 ④ 참가비를 납부하신 경우 환불받을 계좌(은행명, 계좌번호, 예금주)를 입력
    → 관리자 확인 후 환불해 드립니다.

 [파트너 변경 방법] (복식 부서만 해당)
 ① 위 ①~② 와 같이 내 신청 내역 조회
 ② 해당 대회의 '파트너 변경' 버튼 선택
 ③ 새 파트너 이름 검색 후 선택하여 저장
 ※ 팀의 두 선수 중 한 명이 본인 전화번호와 PIN으로 인증한 뒤 변경합니다.
 ※ 같은 부서에 이미 신청된 선수는 파트너로 선택할 수 없습니다.

