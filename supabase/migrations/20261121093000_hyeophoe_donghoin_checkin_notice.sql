-- 제4회 협회장배 동호인 개인복식: 11/22(일) 오전 11시 현장 출전신고 안내 공지 등록
--  일반 공지, 상단 고정. 같은 제목이 이미 있으면 다시 넣지 않는다. 멱등.

insert into public.notices (title, content, pinned, notice_type)
select
  '[동호인] 11/22(일) 오전 11시 현장 출전신고 안내',
  $notice$내일(11월 22일 일)로 순연된 제4회 제주시테니스협회장배 동호인 개인복식 대회의 출전신고를 아래와 같이 안내드립니다.

■ 출전신고
 - 일시: 11월 22일(일) 오전 11시
 - 장소: 대회장 현장
 - 참가하는 모든 팀은 현장에서 출전신고를 해 주시기 바랍니다.

■ 참가가 어려운 경우
 - 내일 참가가 어려운 팀은 앱에서 직접 신청을 취소해 주시기 바랍니다.
 - 앱 취소 및 파트너 변경 기한: 오늘(11월 21일) 17시까지

 [신청 취소 방법]
 ① 앱 하단 '신청확인' 메뉴 → '내 신청 내역'
 ② 전화번호와 PIN 6자리 입력 후 조회 (PIN 초기값은 전화번호 뒷 6자리)
 ③ 해당 대회의 '신청 취소' 버튼 선택
 ④ 참가비를 납부하신 경우 환불받을 계좌(은행명, 계좌번호, 예금주)를 입력
    → 관리자 확인 후 환불해 드립니다.

■ 문의
 - 앱 '건의문의' 게시판에 남겨 주시기 바랍니다.

제주시테니스협회$notice$,
  true,
  'general'
where not exists (
  select 1 from public.notices
   where title = '[동호인] 11/22(일) 오전 11시 현장 출전신고 안내'
);
